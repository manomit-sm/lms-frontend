// Refreshes the OpenAPI snapshots from a running backend and regenerates the TypeScript types.
//   npm run api:generate             fetch from LMS_BACKEND_URL (.env.development), then generate
//   npm run api:generate -- --offline   regenerate the types from the committed snapshots only
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const DOCUMENTS = ['tenant', 'platform'];
const API_DIR = new URL('../packages/api/', import.meta.url);
const offline = process.argv.includes('--offline');

const banner = (name) =>
  `/**\n * Generated by scripts/generate-api.mjs from packages/api/openapi/${name}.json - do not edit.\n */\n\n`;

async function fetchDocument(name) {
  const backend = process.env.LMS_BACKEND_URL;
  if (!backend) {
    throw new Error('LMS_BACKEND_URL is not set (see .env.development)');
  }
  const response = await fetch(new URL(`/v3/api-docs/${name}`, backend));
  if (!response.ok) {
    throw new Error(`GET /v3/api-docs/${name}: ${response.status} - is the backend running?`);
  }
  const document = await response.json();
  // The generated server URL depends on how the backend was reached; it isn't part of the contract.
  delete document.servers;
  return document;
}

await mkdir(new URL('openapi/', API_DIR), { recursive: true });
await mkdir(new URL('src/generated/', API_DIR), { recursive: true });

for (const name of DOCUMENTS) {
  const snapshot = new URL(`openapi/${name}.json`, API_DIR);
  if (!offline) {
    await writeFile(snapshot, JSON.stringify(await fetchDocument(name), null, 2) + '\n');
  }
  const document = JSON.parse(await readFile(snapshot, 'utf8'));
  const ast = await openapiTS(document, { enum: false, exportType: false, alphabetize: true });
  await writeFile(new URL(`src/generated/${name}.ts`, API_DIR), banner(name) + astToString(ast));
  console.log(
    `${name}: ${Object.keys(document.paths).length} paths -> packages/api/src/generated/${name}.ts`,
  );
}
